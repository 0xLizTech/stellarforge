//! Resource baseline for every entry point in every Phase 1/2 contract.
//!
//! Regenerate with:
//!
//! ```text
//! cargo run -p stellarforge-benchmark > docs/benchmarks/resource-baseline.md
//! ```
//!
//! Each entry point is invoked once, with realistic arguments and the
//! minimum state setup it needs (an existing asset, an existing KYC record,
//! and so on), and its resource cost is read immediately afterward via
//! `env.cost_estimate().resources()`, which reports only the most recent
//! top-level invocation. A constructor call is measured the same way, by
//! reading cost estimate right after `env.register(...)`.
//!
//! This is a baseline, not an exhaustive cost model: one representative
//! call per entry point, not every branch (an empty vs. a populated
//! registry page, a cold vs. a warm KYC record, and so on cost differently,
//! and are not captured here). Its job is catching a regression that moves
//! an entry point's cost meaningfully from what it was, not predicting
//! exact mainnet fees.

mod benches;

use soroban_sdk::testutils::cost_estimate::NetworkInvocationResourceLimits;
use soroban_sdk::Env;

struct Row {
    contract: &'static str,
    entry_point: &'static str,
    instructions: i64,
    mem_bytes: i64,
    disk_read_entries: u32,
    memory_read_entries: u32,
    write_entries: u32,
}

fn main() {
    let mut rows = Vec::new();
    rows.extend(benches::registry::run());
    rows.extend(benches::compliance::run());
    rows.extend(benches::governance::run());
    rows.extend(benches::oracle_adapter::run());
    rows.extend(benches::rwa_asset::run());

    print_report(&rows);
}

/// Resource cost of the last invocation made on `env`, labelled for one row
/// of the report. Must be called immediately after the call being measured,
/// before any other invocation (including a read used only for an
/// assertion) overwrites the "last invocation" the host tracks.
fn measure(env: &Env, contract: &'static str, entry_point: &'static str) -> Row {
    let res = env.cost_estimate().resources();
    Row {
        contract,
        entry_point,
        instructions: res.instructions,
        mem_bytes: res.mem_bytes,
        disk_read_entries: res.disk_read_entries,
        memory_read_entries: res.memory_read_entries,
        write_entries: res.write_entries,
    }
}

/// A fresh `Env` with mainnet per-invocation resource limits enforced and
/// every auth mocked, matching the pattern each contract's own tests use
/// (e.g. `registry::tests::assert_directory_accepts_and_pages_after`) so a
/// benchmark run also catches an entry point that would fail mainnet limits
/// outright, not just one whose cost drifted.
fn mainnet_env() -> Env {
    let env = Env::default();
    env.mock_all_auths();
    env.cost_estimate()
        .enforce_resource_limits(NetworkInvocationResourceLimits::mainnet());
    env
}

fn print_report(rows: &[Row]) {
    println!("# Resource Baseline\n");
    println!(
        "Generated by `cargo run -p stellarforge-benchmark`. One representative call per \
         entry point, measured via `env.cost_estimate().resources()` under mainnet \
         per-invocation resource limits (see `tools/benchmark/src/main.rs` for what this \
         does and does not capture)."
    );
    println!();
    println!(
        "| Contract | Entry point | Instructions | Memory (bytes) | Disk reads | Memory reads \
         | Writes |"
    );
    println!("|---|---|---|---|---|---|---|");
    for row in rows {
        println!(
            "| {} | `{}` | {} | {} | {} | {} | {} |",
            row.contract,
            row.entry_point,
            row.instructions,
            row.mem_bytes,
            row.disk_read_entries,
            row.memory_read_entries,
            row.write_entries,
        );
    }
}
